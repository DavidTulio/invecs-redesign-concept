function slugify(text: string) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

export const sampleCars: Car[] = cars.map((car, index) => {
  const id = String(index + 1).padStart(4, "0");
  return {
    ...car,
    id,
    slug: slugify(`${car.year} ${car.make} ${car.model} ${car.variant} ${id}`),
  };
});
